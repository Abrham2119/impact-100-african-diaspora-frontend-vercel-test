/**
 * npm run export:content-schemas — writes the JSON Schema of every CMS section type and collection
 * (declared once in src/features/content/schemas/sectionTypes.ts) to
 * src/features/content/schemas/content-schemas.json. The backend's Joi section registry is tested
 * against this file, so the two sides cannot drift (ARCHITECTURE.md §7.1).
 * Runs with Node's built-in TypeScript support; no extra dependency.
 */
import { writeFileSync } from 'node:fs';
import { JSON_DEFINITIONS } from '../features/content/schemas/fields.ts';
import { COLLECTION_TYPES, SECTION_TYPES } from '../features/content/schemas/sectionTypes.ts';

const OUT = new URL('../features/content/schemas/content-schemas.json', import.meta.url);

const document = {
  $schema: 'http://json-schema.org/draft-07/schema#',
  title: 'Impact 100 CMS content schemas',
  description: 'Generated by `npm run export:content-schemas` from src/features/content/schemas/sectionTypes.ts. Do not edit.',
  definitions: JSON_DEFINITIONS,
  sections: Object.fromEntries(SECTION_TYPES.map((type) => [type.type, type.json])),
  collections: Object.fromEntries(COLLECTION_TYPES.map((type) => [type.key, type.json])),
};

writeFileSync(OUT, `${JSON.stringify(document, null, 2)}\n`);
console.log(`✓ ${SECTION_TYPES.length} section types and ${COLLECTION_TYPES.length} collections → ${OUT.pathname}`);
